/**
 * The shape every language's table has: the English keys, with each string
 * any string and each function taking the same values.
 */
type Widen<T> = {
	readonly [K in keyof T]: T[K] extends string
		? string
		: T[K] extends (...values: infer V) => string
			? (...values: V) => string
			: Widen<T[K]>;
};

